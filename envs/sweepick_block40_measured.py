"""Measured Sweepick 2x2m virtual-floor tabletop smoke, World heading +Y.

This task overrides ONLY the measured Sweepick experiment. It does not mutate
the existing generic SO101, original Sweepick smoke or original robot URDFs.
Uses the modified SO101 base STL generated by build_sweepick_measured_urdf.py.
"""
from copy import deepcopy
from pathlib import Path
import os

import numpy as np
import sapien

from .sweepick_block40 import sweepick_block40
from .utils import create_entity_box
from sweepick_table_frame import (
    BASE_ORIGIN_WORLD_XY,
    TABLE_NOMINAL_WORLD_Z,
    base_to_world,
    world_to_base,
)


class sweepick_block40_measured(sweepick_block40):
    # Final World frame is the original RoboTwin convention, NOT the RViz
    # world==base_footprint preview frame. Robot forward maps to World +Y.
    ROBOT_WORLD_ORIGIN = np.array([0.0, -0.2539, 0.5])
    FLOOR_TOP_WORLD_Z = TABLE_NOMINAL_WORLD_Z
    TABLE_CENTER_WORLD_XY = (0.0, -0.7)
    table_length = 2.0
    table_width = 2.0
    CROP_MIN = np.array([0.15, -0.26, 0.005])
    CROP_MAX = np.array([0.32, 0.26, 0.40])

    def setup_demo(self, **kwargs):
        self._task_crop_enabled = bool(kwargs.get("sweepick_crop_base", False))
        # The parent sweepick_block40.setup_demo sets table_height from
        # FLOOR_TOP_WORLD_Z, then Base_Task creates our 2x2m table.
        kwargs = dict(kwargs)
        kwargs["table_xy_bias"] = list(self.TABLE_CENTER_WORLD_XY)
        super().setup_demo(**kwargs)

    @property
    def tabletop_world_z(self):
        # Base_Task sets table_z_bias BEFORE loading arms, camera and objects.
        return self.FLOOR_TOP_WORLD_Z + float(getattr(self, "table_z_bias", 0.0))

    def _robot_to_world(self, xyz):
        return base_to_world(xyz, tabletop_world_z=self.tabletop_world_z).tolist()

    def load_robot(self, **kwargs):
        # random_table_height changes the table top by table_z_bias. This
        # same delta MUST apply to arm bases, otherwise the relative height
        # and CuRobo local floor proxy would be inconsistent.
        options = deepcopy(kwargs)
        bias = float(self.table_z_bias)
        for key in ("left_embodiment_config", "right_embodiment_config"):
            conf = options[key]
            conf["robot_pose"] = [
                [p[0], p[1], p[2] + bias, *p[3:]] for p in conf["robot_pose"]
            ]
        return super().load_robot(**options)

    def load_camera(self, **kwargs):
        # Preserve OS30A-to-base extrinsic even when randomizing table height.
        options = deepcopy(kwargs)
        conf = options["left_embodiment_config"]
        for camera in conf["static_camera_list"]:
            camera["position"][2] += float(self.table_z_bias)
        return super().load_camera(**options)

    def _load_turtlebot(self):
        path = os.environ.get("SWEEPICK_TURTLEBOT_URDF", "")
        if not path or not Path(path).is_file():
            raise RuntimeError(
                "SWEEPICK_TURTLEBOT_URDF must refer to the team's actual "
                "TurtleBot3 Waffle Pi URDF with its mesh dependencies"
            )
        loader = self.scene.create_urdf_loader()
        loader.fix_root_link = True
        self.turtlebot = loader.load(str(Path(path).resolve()))
        if self.turtlebot is None:
            raise RuntimeError("SAPIEN failed to load TurtleBot Waffle Pi URDF")
        self.turtlebot.set_root_pose(
            sapien.Pose(
                p=[*BASE_ORIGIN_WORLD_XY, self.tabletop_world_z],
                q=[0.7071067811865476, 0.0, 0.0, 0.7071067811865476],
            )
        )

    def _load_mount_collision_proxies(self):
        # Body-frame rails: two 20x20x400mm pieces along local Y.
        # Measured mount centre assumption has NOT been mechanically checked.
        proxies = (
            ("sweepick_front_rail_ASSUMED", [-0.014, 0.0, 0.113],
             [0.010, 0.200, 0.010]),
            ("sweepick_rear_rail_ASSUMED", [-0.106, 0.0, 0.113],
             [0.010, 0.200, 0.010]),
            ("sweepick_os30a_housing_UNVERIFIED", [-0.035, 0.0, 0.4905],
             [0.017, 0.045, 0.0175]),
        )
        self.mount_proxies = []
        for name, xyz, half_size in proxies:
            self.mount_proxies.append(
                create_entity_box(
                    scene=self.scene,
                    pose=sapien.Pose(
                        p=self._robot_to_world(xyz),
                        q=[0.7071067811865476, 0.0, 0.0, 0.7071067811865476],
                    ),
                    half_size=half_size,
                    color=(0.30, 0.34, 0.39),
                    is_static=True,
                    name=name,
                )
            )

    def get_obs(self):
        """Store actual per-frame PointCloud XYZ in TurtleBot base_footprint.

        The existing Camera.get_pcd() projects points to SAPIEN WORLD.
        Convert to base_footprint here, not by pretending World==base.
        Retain columns 3: (RGB) as supplied by Camera.get_pcd.
        """
        result = super().get_obs()
        raw = result.get("pointcloud")
        if isinstance(raw, np.ndarray) and raw.ndim == 2 and raw.shape[1] >= 3:
            pcd = np.array(raw, copy=True)
            pcd[:, :3] = world_to_base(
                pcd[:, :3], tabletop_world_z=self.tabletop_world_z
            )
            if self._task_crop_enabled:
                xyz = pcd[:, :3]
                keep = np.isfinite(xyz).all(axis=1) & (
                    (xyz >= self.CROP_MIN).all(axis=1)
                    & (xyz <= self.CROP_MAX).all(axis=1)
                )
                pcd = pcd[keep]
            result["pointcloud"] = pcd
            self.now_obs["pointcloud"] = np.array(pcd, copy=True)
        return result

    def load_actors(self):
        # Inherited sweepick_block40.load_actors uses _robot_to_world for
        # 40mm block, robot and rails; therefore all share the randomized table
        # top without changing the generic RoboTwin floor-only task.
        super().load_actors()
        print(
            "[SWEEPICK TABLETOP] World heading +Y; 2x2m table "
            f"centre={self.TABLE_CENTER_WORLD_XY}, top_z={self.tabletop_world_z:.4f}; "
            f"TurtleBot base=({BASE_ORIGIN_WORLD_XY[0]:.4f},"
            f"{BASE_ORIGIN_WORLD_XY[1]:.4f},{self.tabletop_world_z:.4f}); "
            "arms from measured YAML, 40mm block centred in base frame "
            "(0.18,0.14,0.021). Saved PointCloud is base_footprint XYZ. "
            "CuRobo chassis/rails collisions NOT validated."
        )
